def get_meta(conn, key: str, default: str = "") -> str:
    row = conn.execute("SELECT v FROM meta WHERE k=?", (key,)).fetchone()
    if row is None:
        return default
    return row["v"] if isinstance(row, dict) else row[0]


def set_meta(conn, key: str, value: str):
    conn.execute(
        "INSERT INTO meta(k,v) VALUES(?,?) ON CONFLICT(k) DO UPDATE SET v=excluded.v",
        (key, value),
    )


def init_db():
    if IS_PG:
        import time as _t

        for stmt in PG_SCHEMA:
            for attempt in range(20):
                try:
                    with _pg().connection() as c:
                        c.execute(stmt)
                        c.commit()
                    break
                except Exception as e:
                    if "already exists" in str(e):
                        break
                    _t.sleep(0.5)
        return
    conn = _connect_sqlite()
    try:
        conn.executescript(SQLITE_SCHEMA)
        conn.commit()
        cols = {r[1] for r in conn.execute("PRAGMA table_info(buckets)").fetchall()}
        if "failed_count" not in cols:
            conn.execute("ALTER TABLE buckets ADD COLUMN failed_count INTEGER NOT NULL DEFAULT 0")
        if "last_checked" not in cols:
            conn.execute("ALTER TABLE buckets ADD COLUMN last_checked TEXT NOT NULL DEFAULT ''")
        if "last_status" not in cols:
            conn.execute("ALTER TABLE buckets ADD COLUMN last_status TEXT NOT NULL DEFAULT ''")
        conn.commit()
    finally:
        conn.close()


def insert_returning_id(conn, sql: str, params: tuple) -> int:
    sql = sql.strip().rstrip(";")
    if IS_PG:
        cur = conn.execute(sql + " RETURNING id", params)
        return int(cur.fetchone()["id"])
    cur = conn.execute(sql, params)
    return cur.lastrowid

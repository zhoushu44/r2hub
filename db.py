import os
import random
import sqlite3
import time
from contextlib import contextmanager

DB_PATH = os.environ.get("DB_PATH", os.path.join(os.path.dirname(__file__), "data", "r2hub.db"))
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()
IS_PG = DATABASE_URL.startswith(("postgresql://", "postgres://"))

_pg_pool = None


def _pg():
    global _pg_pool
    if _pg_pool is None:
        from psycopg_pool import ConnectionPool

        max_size = int(os.environ.get("PG_POOL_MAX", "25"))
        _pg_pool = ConnectionPool(DATABASE_URL, min_size=1, max_size=max_size, open=True,
                                  kwargs={"autocommit": False})
    return _pg_pool


class _Cursor:
    def __init__(self, rows):
        self._rows = rows

    def fetchone(self):
        return self._rows[0] if self._rows else None

    def fetchall(self):
        return self._rows


class _PgConn:
    def __init__(self, conn):
        self._c = conn

    def execute(self, sql, params=()):
        cur = self._c.execute(sql.replace("?", "%s"), tuple(params))
        if cur.description:
            cols = [d.name for d in cur.description]
            return _Cursor([dict(zip(cols, row)) for row in cur.fetchall()])
        return _Cursor([])

    def commit(self):
        pass


class _SqliteConn:
    RETRIES = int(os.environ.get("SQLITE_LOCK_RETRIES", "60"))

    def __init__(self, conn):
        self._c = conn

    def execute(self, sql, params=()):
        delay = 0.03
        last = None
        for attempt in range(self.RETRIES):
            try:
                return self._c.execute(sql, tuple(params))
            except sqlite3.OperationalError as e:
                msg = str(e).lower()
                if ("locked" in msg or "busy" in msg) and attempt < self.RETRIES - 1:
                    last = e
                    time.sleep(delay + random.random() * delay)
                    delay = min(delay * 1.7, 0.6)
                    continue
                raise
        raise last

    def commit(self):
        self._c.commit()


def _connect_sqlite() -> sqlite3.Connection:
    d = os.path.dirname(DB_PATH)
    if d:
        os.makedirs(d, exist_ok=True)
    conn = sqlite3.connect(DB_PATH, timeout=15)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA busy_timeout=15000")
    conn.execute("PRAGMA foreign_keys=ON")
    return conn


@contextmanager
def db():
    if IS_PG:
        with _pg().connection() as c:
            yield _PgConn(c)
    else:
        conn = _connect_sqlite()
        try:
            yield _SqliteConn(conn)
            conn.commit()
        finally:
            conn.close()


